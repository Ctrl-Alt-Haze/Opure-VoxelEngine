// ============================================================================
//  Opure_Metrics.h
//  Opure-VoxelEngine -- runtime self-monitoring and eval harness.
// ============================================================================
//  WHAT THIS IS
//  ------------
//  "Metacognition" for an LLM means the model can report on its own state:
//  - Confidence (entropy of output distribution)
//  - Out-of-distribution detection (logit norms, attention patterns)
//  - KV cache pressure
//  - Per-layer timing anomalies
//
//  WHAT THIS IS NOT
//  ----------------
//  This does NOT make the model "smarter" or "self-improve". Real self-
//  improvement needs a backward pass, a dataset, an optimizer, and a verified
//  eval loop showing Δloss < 0. This is the OBSERVABILITY LAYER that such
//  a loop would stand on — without it, you can't measure improvement.
//
//  USAGE
//  -----
//  Call Engine::SnapshotMetrics() after each token to get a MetricsSnapshot.
//  The eval harness (Opure_Eval.cpp) runs a fixed benchmark suite and compares
//  against a stored baseline to detect regression/improvement.
// ============================================================================

#pragma once

#include <cstdint>
#include <vector>
#include <string>

namespace opure::engine {

// ---------------------------------------------------------------------------
//  A single measurement snapshot, taken after one forward pass.
// ---------------------------------------------------------------------------
struct MetricsSnapshot
{
    uint64_t timestampMs = 0;

    // Per-layer timing (ms). Size = num_layers.
    std::vector<float> layerTimesMs;

    // KV cache occupancy: fraction of max_seq used. 0..1.
    float kvOccupancy = 0.0f;

    // Logit entropy (nats). Low = confident, high = uncertain.
    float logitEntropy = 0.0f;

    // Current tokens/sec (instantaneous).
    float tokensPerSec = 0.0f;

    // Memory pressure: allocated VRAM / available VRAM. 0..1 (can exceed 1 if overcommitted).
    float memoryPressure = 0.0f;

    // Speculative acceptance rate (0..1). -1 if speculative decode disabled.
    float speculativeAcceptance = -1.0f;

    // Logit L2 norm (detects distribution shift).
    float logitNorm = 0.0f;

    // Max attention score (detects sharp vs flat attention).
    float maxAttnScore = 0.0f;
};

// ---------------------------------------------------------------------------
//  Configuration for the eval harness.
// ---------------------------------------------------------------------------
struct EvalConfig
{
    // Path to baseline JSON (generated by Opure_Eval --baseline).
    std::string baselinePath;

    // Path to write current results JSON.
    std::string outputPath;

    // If true, fail on ANY regression (used in CI).
    bool failOnRegression = false;

    // Tolerance for logit drift (relative).
    float logitDriftTol = 0.01f;

    // Tolerance for tokens/sec regression.
    float speedDriftTol = 0.05f;

    // Number of benchmark prompts to run.
    uint32_t numPrompts = 10;
};

// ---------------------------------------------------------------------------
//  Result of running the eval suite.
// ---------------------------------------------------------------------------
struct EvalResult
{
    bool passed = false;
    std::string summary;

    // Per-prompt results.
    struct PromptResult {
        std::string prompt;
        float tokensPerSec = 0.0f;
        float logitEntropy = 0.0f;
        float drift = 0.0f;          // relative to baseline
        bool regressed = false;
    };
    std::vector<PromptResult> prompts;

    // Aggregate.
    float meanTokensPerSec = 0.0f;
    float meanEntropy = 0.0f;
    float worstDrift = 0.0f;
};

// ---------------------------------------------------------------------------
//  Metrics collector -- attached to a VoxelEngine instance.
//  Forward declaration; implementation in Opure_Metrics.cpp.
// ---------------------------------------------------------------------------
class VoxelEngine;  // forward decl

class MetricsCollector
{
public:
    explicit MetricsCollector(VoxelEngine& engine);

    // Takes a snapshot after a token is generated.
    MetricsSnapshot Snapshot();

    // Recomputes entropy and L2 norm from the last forward pass's logits,
    // reading the vector back if the engine has not done so already. Returns
    // -1.0f when no forward pass has run yet, so "unknown" is distinguishable
    // from a genuine 0.0 (a perfectly peaked distribution still has entropy
    // slightly above zero).
    float ComputeLogitEntropy();
    float ComputeLogitNorm();

    // Maximum attention weight in the last attention pass.
    //
    // Always -1.0f: the flash-decode kernel reduces over keys in registers and
    // never writes the weight matrix out, so there is nothing on the GPU to
    // read. Retaining it would cost a vocab-length score buffer per layer.
    // Reported as unavailable rather than 0.0, which would read as "attention
    // is uniformly diffuse" -- the opposite of the usual sign.
    float ComputeMaxAttnScore() const;

private:
    VoxelEngine& engine_;
    std::vector<float> layerTimings_;
    uint64_t lastTokenTimeMs_ = 0;
};

// ---------------------------------------------------------------------------
//  Eval harness -- runs a fixed benchmark suite against a baseline.
// ---------------------------------------------------------------------------
class VoxelEngine;  // forward decl

class EvalHarness
{
public:
    explicit EvalHarness(const EvalConfig& cfg);

    // Runs the full eval suite on the given engine.
    EvalResult Run(VoxelEngine& engine);

    // Generates a baseline file (run once, then commit to repo).
    void GenerateBaseline(VoxelEngine& engine);

private:
    EvalConfig cfg_;
    std::vector<std::string> prompts_;
};

} // namespace opure::engine